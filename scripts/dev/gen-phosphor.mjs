// Generates crates/app/src/phosphor.rs (path data of the Phosphor icons fm uses) and the Phosphor
// part of THIRD-PARTY-NOTICES.txt from the pinned npm package. Run: node scripts/dev/gen-phosphor.mjs
// Adding an icon: put its Phosphor name in NAMES and run this again.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const VERSION = '2.1.1'
const BASE = `https://cdn.jsdelivr.net/npm/@phosphor-icons/core@${VERSION}`
const NAMES = [
  // sidebar
  'clock-counter-clockwise', 'house', 'monitor', 'file-text', 'download-simple', 'image', 'music-notes', 'film-strip', 'cloud',
  'hard-drive', 'hard-drives', 'usb', 'network', 'desktop-tower', 'folder', 'eject', 'trash', 'file-magnifying-glass',
  // toolbar, headers, tabs, states
  'sidebar-simple', 'arrow-left', 'arrow-right', 'dots-three', 'magnifying-glass', 'squares-four', 'list-bullets', 'columns',
  'slideshow', 'caret-up', 'caret-down', 'caret-right', 'plus', 'x', 'push-pin', 'warning', 'folder-open',
  // file types: 16 px glyphs and the glyph inside the large page
  'file', 'file-zip', 'file-image', 'file-audio', 'file-video', 'file-code', 'disc', 'text-align-left', 'hash', 'article',
  'archive', 'table', 'presentation-chart', 'text-aa', 'brackets-curly', 'code',
]
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const pascal = n => n.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('')

async function get(url) {
  const r = await fetch(url)
  if (!r.ok) throw new Error(`${r.status} ${url}`)
  return r.text()
}
// Every Phosphor bold/fill icon is a 256×256 box of <path> elements with no fill-rule or transform;
// anything else would be drawn wrong, so it stops the generator.
function paths(svg, url) {
  if (!/viewBox="0 0 256 256"/.test(svg)) throw new Error(`unexpected viewBox: ${url}`)
  const other = svg.replace(/<\/?svg[^>]*>/g, '').replace(/<path d="[^"]*"\/>/g, '').trim()
  if (other) throw new Error(`unexpected content in ${url}: ${other.slice(0, 80)}`)
  if (/fill-rule|transform|opacity/.test(svg)) throw new Error(`unexpected attribute in ${url}`)
  return [...svg.matchAll(/<path d="([^"]*)"\/>/g)].map(m => m[1]).join(' ')
}

const arms = []
for (const n of NAMES) {
  for (const w of ['bold', 'fill']) {
    const url = `${BASE}/assets/${w}/${n}-${w}.svg`
    const d = paths(await get(url), url)
    arms.push(`            (Ico::${pascal(n)}, Weight::${w === 'bold' ? 'Bold' : 'Fill'}) => "${d}",`)
  }
}
const rs = `//! Phosphor Icons ${VERSION} (MIT, see THIRD-PARTY-NOTICES.txt): SVG path data in a 256×256 box.
//! Generated by scripts/dev/gen-phosphor.mjs from @phosphor-icons/core@${VERSION}; do not edit by hand.

/// A Phosphor icon, named as on phosphoricons.com.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Ico {
${NAMES.map(n => `    ${pascal(n)},`).join('\n')}
}

/// Bold reads at 16 px on a 100 % screen; Fill marks the selected place.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Weight {
    Bold,
    Fill,
}

impl Ico {
    pub const ALL: [Ico; ${NAMES.length}] = [${NAMES.map(n => `Ico::${pascal(n)}`).join(', ')}];

    pub fn path(self, w: Weight) -> &'static str {
        match (self, w) {
${arms.join('\n')}
        }
    }
}
`
fs.writeFileSync(path.join(ROOT, 'crates', 'app', 'src', 'phosphor.rs'), rs)

const lic = await get(`${BASE}/LICENSE`)
const notices = `Third-party notices for Soubory (fm)

fm draws its sidebar, toolbar and file-type icons with Phosphor Icons ${VERSION}
(https://phosphoricons.com, @phosphor-icons/core), used under the MIT License:

${lic.trim()}
`
fs.writeFileSync(path.join(ROOT, 'THIRD-PARTY-NOTICES.txt'), notices.replace(/\r?\n/g, '\r\n'))
console.log(`phosphor.rs: ${NAMES.length} icons; THIRD-PARTY-NOTICES.txt written`)
